def _find_col(df: pd.DataFrame, candidates: list[str],
              label: str, logger) -> str | None:
    """
    Return the first matching column name (exact, then case-insensitive).
    Logs clearly what it found or failed to find.
    """
    cols_lower = {c.lower(): c for c in df.columns}
    for cand in candidates:
        if cand in df.columns:
            logger.info(f"  Column [{label}]: matched '{cand}' (exact)")
            return cand
        if cand.lower() in cols_lower:
            actual = cols_lower[cand.lower()]
            logger.info(f"  Column [{label}]: matched '{actual}' "
                        f"(case-insensitive match for '{cand}')")
            return actual
    logger.warning(
        f"  Column [{label}]: NOT FOUND.  Tried: {candidates}.\n"
        f"  Available columns: {sorted(df.columns.tolist())}\n"
        f"  Fix: add correct name under column_aliases in pipeline_config.yaml."
    )
    return None


def _unique_pairs(df: pd.DataFrame, dom_col: str, prot_col: str) -> pd.DataFrame:
    """
    Return a deduplicated (protein_accession, domain_type_id) table.

    WHY THIS MATTERS (FIX-A / FIX-B):
      _build_domain_protein_map builds a SET: domain → {proteins}.
      With avg 4-5 rows per protein, row-level permutation barely changes
      that set because duplicate protein labels cancel out.
      Operating on unique pairs removes this artefact so permutation
      actually changes which proteins are associated with which domains.
    """
    return (df[[prot_col, dom_col]]
            .drop_duplicates()
            .reset_index(drop=True))


def _run_one(fg_proteins: set, bg_proteins: set,
             d2p_fg: dict, d2p_bg: dict) -> tuple[int, float, float, int]:
    """
    Run enrichment and return (n_sig, max_or, median_or, n_domain_types).
    n_domain_types = number of domain types present in d2p_fg (denominator
    for enrichment_rate).
    """
    res         = run_enrichment(fg_proteins, bg_proteins, d2p_fg, d2p_bg, min_fg=1)
    n_sig       = int((res["fdr"] < 0.05).sum())    if not res.empty else 0
    max_or      = float(res["odds_ratio"].max())    if not res.empty else 0.0
    med_or      = float(res["odds_ratio"].median()) if not res.empty else 0.0
    n_dom_types = len(d2p_fg)
    return n_sig, max_or, med_or, n_dom_types


def _matched_sample(fg_domain_counts: pd.Series,
                    bg_domain_counts: pd.Series,
                    rng: np.random.Generator) -> set[str]:
    """
    Quartile-stratified sampling: draw background proteins whose per-protein
    domain-count distribution matches the foreground distribution.
    (FIX-C: prevents SwissProt domain-richness bias from inflating n_sig.)
    """
    n_fg = len(fg_domain_counts)
    if len(bg_domain_counts) < n_fg:
        chosen = rng.choice(bg_domain_counts.index.tolist(),
                            size=n_fg, replace=False)
        return set(chosen)

    q_edges = np.unique(np.percentile(fg_domain_counts.values, [0, 25, 50, 75, 100]))
    q_edges[-1] += 1e-9
    fg_bins = np.digitize(fg_domain_counts.values, q_edges[1:])
    bg_bins = np.digitize(bg_domain_counts.values, q_edges[1:])

    sampled: list[str] = []
    available_bg = bg_domain_counts.copy()

    for bucket in range(len(q_edges) - 1):
        need = int((fg_bins == bucket).sum())
        if need == 0:
            continue
        pool_ids = available_bg.index[
            np.isin(available_bg.index, bg_domain_counts.index[bg_bins == bucket])
        ]
        if len(pool_ids) < need:
            pool_ids = available_bg.index
        idx = rng.choice(len(pool_ids), size=min(need, len(pool_ids)), replace=False)
        chosen = pool_ids[idx].tolist()
        sampled.extend(chosen)
        available_bg = available_bg.drop(chosen)

    shortfall = n_fg - len(sampled)
    if shortfall > 0 and len(available_bg) > 0:
        extra = rng.choice(available_bg.index.tolist(),
                           size=min(shortfall, len(available_bg)), replace=False)
        sampled.extend(extra.tolist())

    return set(sampled)


def _empirical_stats(real_val: float, rand_vals: np.ndarray,
                     metric_name: str, logger) -> dict:
    """
    Compute empirical p-value and percentile rank.
    (FIX-D: replaces Mann-Whitney called with a single-element sample.)
    """
    n = len(rand_vals)
    if n < 10:
        return {}
    empirical_p = float(np.mean(rand_vals >= real_val))
    pct_rank    = float(np.mean(rand_vals < real_val)) * 100
    direction   = "ENRICHED" if real_val > np.mean(rand_vals) else "DEPLETED"
    logger.info(
        f"    [{metric_name}] real={real_val:.3f}, "
        f"random mean={np.mean(rand_vals):.3f}±{np.std(rand_vals):.3f}, "
        f"ratio={real_val / max(np.mean(rand_vals), 1e-9):.3f}×, "
        f"empirical p={empirical_p:.4f}, "
        f"pct={pct_rank:.1f}% [{direction}]"
    )
    return {"empirical_p": empirical_p, "pct_rank": pct_rank, "direction": direction}


